"""Create synthetic noise clips in data/noise/ (babble, fan, traffic) and record them in NOTICE.

    uv run python scripts/make_noise.py

Babble uses dev-split Timbre clips only, so no test sentence appears inside the noise.
Replace or add real recordings later, then re-run build_conditions.py.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import numpy as np  # noqa: E402
import soundfile as sf  # noqa: E402

from kuralcheck.audio.conditions import load_clean  # noqa: E402
from kuralcheck.audio.synth_noise import SR, babble, fan, traffic  # noqa: E402
from kuralcheck.data import NOISE_DIR, load_sentences, utterances  # noqa: E402

SECONDS = 30.0
NOTICE_LINES = {
    "babble_synthetic.wav": "babble_synthetic.wav: synthetic crowd babble, 6 overlapping talkers built from KuralCheck dev-split Timbre clips (CC BY 4.0, KuralCheck team)",
    "fan_synthetic.wav": "fan_synthetic.wav: synthetic fan noise, pink noise + weak 100 Hz hum, generated by scripts/make_noise.py (CC BY 4.0, KuralCheck team)",
    "traffic_synthetic.wav": "traffic_synthetic.wav: synthetic traffic rumble, brown noise with passing-vehicle swells, generated by scripts/make_noise.py (CC BY 4.0, KuralCheck team)",
}


def main(seed: int = 42) -> int:
    sys.stdout.reconfigure(encoding="utf-8")
    rng = np.random.default_rng(seed)
    dev = [u for u in utterances(load_sentences()) if u.sentence.split == "dev" and u.sentence.source == "timbre"]
    clips = [load_clean(u.source_audio) for u in dev if u.source_audio.exists()]
    if not clips:
        print("No dev-split Timbre clips found: run scripts/synthesize_set.py first.")
        return 1
    NOISE_DIR.mkdir(parents=True, exist_ok=True)
    for name, data in (
        ("babble_synthetic.wav", babble(clips, SECONDS, rng)),
        ("fan_synthetic.wav", fan(SECONDS, rng)),
        ("traffic_synthetic.wav", traffic(SECONDS, rng)),
    ):
        sf.write(NOISE_DIR / name, data, SR, subtype="PCM_16")
        print(f"  wrote data/noise/{name} ({SECONDS:.0f} s)")

    notice = NOISE_DIR / "NOTICE"
    lines = notice.read_text(encoding="utf-8").splitlines() if notice.exists() else []
    for entry in NOTICE_LINES.values():
        key = entry.split(":")[0]
        lines = [ln for ln in lines if not ln.startswith(key)] + [entry]
    notice.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("  updated data/noise/NOTICE")
    return 0


if __name__ == "__main__":
    sys.exit(main())
